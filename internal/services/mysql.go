func init() {
	// The driver prints every failed readiness probe to stderr otherwise.
	_ = mysql.SetLogger(log.New(io.Discard, "", 0))
}

// Secrets lives in data/devstack/secrets.toml. The password is saved before it
// is applied, so a crash in between can be recovered on the next start.
type Secrets struct {
	MySQLRootPassword string `toml:"mysql_root_password"`
	MySQLRootApplied  bool   `toml:"mysql_root_applied"`
}

func SecretsPath(st *model.Stack) string { return filepath.Join(st.Data, "devstack", "secrets.toml") }

func LoadSecrets(st *model.Stack) (Secrets, error) {
	var s Secrets
	_, err := toml.DecodeFile(SecretsPath(st), &s)
	if errors.Is(err, os.ErrNotExist) {
		return s, nil
	}
	return s, err
}

func saveSecrets(st *model.Stack, s Secrets) error {
	path := SecretsPath(st)
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	f, err := os.OpenFile(path, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o600)
	if err != nil {
		return err
	}
	fmt.Fprintln(f, "# Generated by devstack. Local credentials; do not commit or share.")
	if err := toml.NewEncoder(f).Encode(s); err != nil {
		f.Close()
		return err
	}
	return f.Close()
}

func MySQLSpec(st *model.Stack, logs *Logs) (supervisor.Spec, error) {
	m := st.MySQL
	if m.Build.Flavor != "mysql" {
		return supervisor.Spec{}, fmt.Errorf("mysql: %s builds are not supported yet (found %s)", m.Build.Flavor, m.Build.Dir)
	}
	w, err := logs.Get("mysql")
	if err != nil {
		return supervisor.Spec{}, err
	}
	args := []string{"--defaults-file=" + m.INIPath, "--console"}
	return supervisor.Spec{
		Name: "mysql", Group: "mysql", Version: m.Build.Version.String(), Ports: []int{m.Port},
		Path: m.Build.Exe, Args: args, Dir: m.Build.Dir, Log: w,
		Before:       func(ctx context.Context) error { return mysqlInit(ctx, st, w) },
		Ready:        func(ctx context.Context) error { db, err := RootDB(ctx, st); closeDB(db); return err },
		ReadyTimeout: 90 * time.Second,
		After:        func(ctx context.Context) error { return ensureRootPassword(ctx, st, w) },
		Stop: func(ctx context.Context) error {
			db, err := RootDB(ctx, st)
			if err != nil {
				return err
			}
			defer db.Close()
			_, err = db.ExecContext(ctx, "SHUTDOWN")
			return err
		},
		StopTimeout: 60 * time.Second,
		CmdKey:      key(m.Build.Exe, args) + m.DataDir,
		ConfKey:     fileKey(m.INIPath),
	}, nil
}

// mysqlInit creates the datadir on first run. Root starts with no password;
// ensureRootPassword sets one as soon as the server is up.
func mysqlInit(ctx context.Context, st *model.Stack, log io.Writer) error {
	m := st.MySQL
	if entries, err := os.ReadDir(m.DataDir); err == nil && len(entries) > 0 {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(m.DataDir), 0o755); err != nil {
		return err
	}
	// mysqld --initialize insists that the datadir is missing or empty.
	os.Remove(m.DataDir)
	fmt.Fprintf(log, "devstack: initializing %s\n", m.DataDir)
	ctx, cancel := context.WithTimeout(ctx, 5*time.Minute)
	defer cancel()
	cmd := exec.CommandContext(ctx, m.Build.Exe, "--defaults-file="+m.INIPath, "--initialize-insecure", "--console")
	cmd.Dir = m.Build.Dir
	cmd.Stdout, cmd.Stderr = log, log
	winproc.HideWindow(cmd)
	if err := cmd.Run(); err != nil {
		os.RemoveAll(m.DataDir) // half-initialized datadirs refuse to start; let the next try start clean
		return fmt.Errorf("initialize datadir: %w (see logs/mysql.log)", err)
	}
	return nil
}

// RootDB connects as root, trying the saved password and then an empty one
// (the state right after --initialize-insecure).
func RootDB(ctx context.Context, st *model.Stack) (*sql.DB, error) {
	sec, err := LoadSecrets(st)
	if err != nil {
		return nil, err
	}
	candidates := []string{""}
	if sec.MySQLRootPassword != "" {
		candidates = []string{sec.MySQLRootPassword, ""}
		if !sec.MySQLRootApplied {
			candidates = []string{"", sec.MySQLRootPassword}
		}
	}
	var last error
	for _, pw := range candidates {
		db, err := openRoot(st, pw)
		if err != nil {
			return nil, err
		}
		if last = db.PingContext(ctx); last == nil {
			return db, nil
		}
		db.Close()
		var me *mysql.MySQLError
		if !errors.As(last, &me) || me.Number != 1045 { // 1045 = access denied; anything else won't improve with another password
			break
		}
	}
	return nil, last
}

func openRoot(st *model.Stack, password string) (*sql.DB, error) {
	cfg := mysql.NewConfig()
	cfg.User = "root"
	cfg.Passwd = password
	cfg.Net = "tcp"
	cfg.Addr = "127.0.0.1:" + strconv.Itoa(st.MySQL.Port)
	cfg.Timeout = 2 * time.Second
	db, err := sql.Open("mysql", cfg.FormatDSN())
	if err != nil {
		return nil, err
	}
	db.SetMaxOpenConns(1)
	return db, nil
}

func ensureRootPassword(ctx context.Context, st *model.Stack, log io.Writer) error {
	sec, err := LoadSecrets(st)
	if err != nil {
		return err
	}
	if sec.MySQLRootApplied {
		return nil
	}
	if sec.MySQLRootPassword == "" {
		sec.MySQLRootPassword = randomPassword(24)
		if err := saveSecrets(st, sec); err != nil {
			return err
		}
	}
	db, err := openRoot(st, "")
	if err != nil {
		return err
	}
	defer db.Close()
	if err := db.PingContext(ctx); err != nil {
		// Already has a password (e.g. an existing datadir). Check ours works.
		db2, err2 := openRoot(st, sec.MySQLRootPassword)
		if err2 == nil {
			defer db2.Close()
			if db2.PingContext(ctx) == nil {
				sec.MySQLRootApplied = true
				return saveSecrets(st, sec)
			}
		}
		return fmt.Errorf("root has a password devstack doesn't know; put it in %s as mysql_root_password and set mysql_root_applied = true", SecretsPath(st))
	}
	// The password is alphanumeric, so it needs no escaping.
	if _, err := db.ExecContext(ctx, "ALTER USER 'root'@'localhost' IDENTIFIED BY '"+sec.MySQLRootPassword+"'"); err != nil {
		return fmt.Errorf("set root password: %w", err)
	}
	sec.MySQLRootApplied = true
	fmt.Fprintln(log, "devstack: root password set; see `devstack db creds`")
	return saveSecrets(st, sec)
}

func randomPassword(n int) string {
	const alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnpqrstuvwxyz23456789"
	b := make([]byte, n)
	for i := range b {
		k, _ := rand.Int(rand.Reader, big.NewInt(int64(len(alphabet))))
		b[i] = alphabet[k.Int64()]
	}
	return string(b)
}

func closeDB(db *sql.DB) {
	if db != nil {
		db.Close()
	}
}
